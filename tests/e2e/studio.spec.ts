import { test, expect } from '@playwright/test';
import type { Project } from '../../packages/project-schema';
test('editor, persistência, preview responsivo e isolamento', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'BTRK Forge STUDIO' })).toBeVisible();
  await expect(page.getByTestId('node')).toHaveCount(8);
  await page.getByRole('button', { name: '+ Constante' }).click();
  await expect(page.getByTestId('node')).toHaveCount(9);
  await page.getByLabel('Texto do botão').fill('Incrementar');
  await page.reload();
  await expect(page.getByTestId('node')).toHaveCount(9);
  await expect(page.getByLabel('Texto do botão')).toHaveValue('Incrementar');
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  const frame = page.frameLocator('iframe');
  await expect(frame.getByRole('button', { name: 'Incrementar' })).toBeVisible();
  await frame.getByRole('button').click();
  await expect(frame.getByLabel('Estado')).toHaveText('1');
  await frame.getByRole('button').click();
  await expect(frame.getByLabel('Estado')).toHaveText('2');
  await page.getByLabel('Viewport').selectOption('mobile');
  await expect(page.locator('iframe')).toHaveJSProperty('clientWidth', 373);
  const preview = page.frames().find(f => f.url() === 'about:srcdoc')!;
  const isolation = await preview.evaluate(() => {
    let parentDenied = false, storageDenied = false;
    try { void parent.document.body; } catch { parentDenied = true; }
    try { void localStorage.length; } catch { storageDenied = true; }
    return { parentDenied, storageDenied, nativeBridge: '__TAURI_INTERNALS__' in window };
  });
  expect(isolation).toEqual({ parentDenied: true, storageDenied: true, nativeBridge: false });
  await page.screenshot({ path: 'artifacts/studio-preview.png', fullPage: true });
  expect(errors).toEqual([]);
});
test('arraste, zoom e reconexão persistem no modelo independente', async ({ page }) => {
  await page.goto('/');
  const node = page.getByTestId('node').filter({ has: page.getByTestId('title').filter({ hasText: /^Constante · 1$/ }) });
  await expect(node).toBeVisible();
  const title = await node.getByTestId('title').boundingBox();
  await page.mouse.move(title!.x + 20, title!.y + 8); await page.mouse.down();
  await page.mouse.move(title!.x + 60, title!.y + 38, { steps: 10 }); await page.mouse.up();
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('btrk-forge:phase0:project')!) as Project);
  await expect.poll(async () => (await read()).graph.nodes.find(n => n.id === 'one')!.position.x).not.toBe(0);
  const position = (await read()).graph.nodes.find(n => n.id === 'one')!.position;
  const width = (await node.boundingBox())!.width;
  await node.hover(); await page.mouse.wheel(0, -200);
  await expect.poll(async () => (await node.boundingBox())!.width).not.toBe(width);
  await page.getByRole('button', { name: 'Enquadrar' }).click();
  const sum = page.getByTestId('node').filter({ has: page.getByTestId('title').filter({ hasText: /^Somar$/ }) });
  const input = sum.getByTestId('input-b').getByTestId('input-socket');
  const source = node.getByTestId('output-socket');
  const from = await input.boundingBox();
  await page.mouse.move(from!.x + from!.width / 2, from!.y + from!.height / 2); await page.mouse.down();
  const graphBox = await page.getByTestId('graph').boundingBox();
  await page.mouse.move(graphBox!.x + 12, graphBox!.y + 12, { steps: 12 }); await page.mouse.up();
  await expect.poll(async () => (await read()).graph.connections.length).toBe(7);
  await page.reload();
  await expect(page.getByTestId('node')).toHaveCount(8);
  await expect.poll(async () => (await read()).graph.connections.length).toBe(7);
  const to = await input.boundingBox(); const start = await source.boundingBox();
  await page.mouse.move(start!.x + start!.width / 2, start!.y + start!.height / 2); await page.mouse.down();
  await page.mouse.move(to!.x + to!.width / 2, to!.y + to!.height / 2, { steps: 12 }); await page.mouse.up();
  await expect.poll(async () => (await read()).graph.connections.some(c => c.source === 'one' && c.target === 'sum' && c.input === 'b')).toBe(true);
  await page.reload();
  await expect.poll(async () => (await read()).graph.nodes.find(n => n.id === 'one')!.position).toEqual(position);
  await expect(page.getByTestId('node')).toHaveCount(8);
});
test('JSON inválido não substitui modelo, salvamento e abertura', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Salvar JSON' }).click();
  const download = await downloadPromise; await download.saveAs('artifacts/project.btrk.json');
  await page.locator('input[type=file]').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"schemaVersion":999}') });
  await expect(page.getByRole('status')).toContainText('Erro');
  await expect(page.getByTestId('node')).toHaveCount(8);
  await page.locator('input[type=file]').setInputFiles('artifacts/project.btrk.json');
  await expect(page.getByRole('status')).toHaveText('Projeto validado e carregado');
  await page.getByRole('button', { name: 'Modelo JSON' }).click();
  await expect(page.locator('.monaco-editor').first()).toBeVisible();
  expect(errors).toEqual([]);
});
